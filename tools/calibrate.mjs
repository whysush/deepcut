// Calibrates every hole and writes js/data/calibration.js.
// Run after editing the course or physics constants:  node tools/calibrate.mjs
import { writeFileSync } from 'node:fs';
import { HOLES } from '../js/course.js';
import { prepareHole, calibrate } from '../js/physics.js';

const out = [];
for (const [i, hole] of HOLES.entries()) {
  const t0 = performance.now();
  const c = calibrate(prepareHole(hole), 3600);
  if (!c) { console.error(`hole ${i + 1} (${hole.name}): NO HOLE-IN-ONE LINE FOUND`); process.exitCode = 1; out.push({}); continue; }
  console.log(`hole ${i + 1} ${hole.name.padEnd(18)} vmax ${c.vmax.toFixed(1)}  ace ${(c.aceAngle * 180 / Math.PI).toFixed(2)}°  window ${c.aceWindowDeg.toFixed(2)}°  sink ${c.lo.toFixed(0)}-${c.hi.toFixed(0)}  (${(performance.now() - t0).toFixed(0)} ms)`);
  out.push({ vmax: +c.vmax.toFixed(2), aceAngle: +c.aceAngle.toFixed(5), aceWindowDeg: +c.aceWindowDeg.toFixed(2) });
}
writeFileSync(new URL('../js/data/calibration.js', import.meta.url),
  `// Generated by tools/calibrate.mjs — do not edit by hand.\nexport const CALIBRATION = ${JSON.stringify(out, null, 1)};\n`);
